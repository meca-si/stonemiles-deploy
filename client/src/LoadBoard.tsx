function FeeInvoiceCard({
  inv,
  canRecord,
  setBanner,
  onRecorded,
}: {
  inv: FeeInvoice;
  canRecord: boolean;
  setBanner: (s: string | null) => void;
  onRecorded: () => void;
}) {
  const [rail, setRail] = useState<"ach" | "debit" | "crypto">("ach");
  const [reference, setReference] = useState("");
  const [amount, setAmount] = useState("");
  const [busy, setBusy] = useState(false);
  const [cardBusy, setCardBusy] = useState(false);
  const unpaid = inv.status !== "paid" && inv.balanceDue > 0;
  const payByCard = () => {
    if (cardBusy) return;
    setCardBusy(true);
    void api
      .createDispatchFeeCheckout({
        loadId: inv.loadId,
        returnBase: window.location.origin + window.location.pathname,
      })
      .then((res) => {
        if (res.error) {
          setBanner(res.error);
          return;
        }
        if (res.available && res.url) {
          if (res.sessionId) {
            try {
              window.localStorage.setItem(
                "stonemiles.pendingStripeCheckout",
                JSON.stringify({ sessionId: res.sessionId, loadId: inv.loadId }),
              );
            } catch {
              // Storage unavailable (private mode, quota) — the checkout
              // still opens; the desk can sync it manually afterwards.
            }
          }
          window.open(res.url, "_blank", "noreferrer");
          setBanner(
            `Stripe checkout opened for the load #${inv.loadId} dispatch fee — once the card payment completes, record/sync it from the desk.`,
          );
        } else {
          setBanner(res.note ?? "Debit card payment is being set up — it opens when RUGGS LLC connects its card processor.");
        }
        onRecorded();
      })
      .catch(() => setBanner("Couldn't open the card checkout — check your connection and try again."))
      .finally(() => setCardBusy(false));
  };
  return (
    <article className="rounded-2xl border border-[var(--border)] bg-[var(--surface2)] p-3.5" aria-label={`Dispatch fee invoice for load ${inv.loadId}`}>
      <div className="flex items-start justify-between gap-2">
        <div className="min-w-0">
          <div className="font-condensed text-lg font-bold leading-tight">
            Load #{inv.loadId} — {inv.lane}
            {inv.probe && <span className="ml-2 rounded-full bg-[var(--surface)] px-2 py-0.5 text-[11px] font-bold text-[var(--accent)]">PROBE</span>}
          </div>
          <div className="mt-0.5 text-xs text-[var(--dim)]">
            Carrier @{inv.carrierUsername} · delivered {new Date(inv.deliveredAt).toLocaleString([], { month: "short", day: "numeric", hour: "numeric", minute: "2-digit" })}
            {inv.packetRef ? ` · packet ${inv.packetRef}` : ""}
          </div>
        </div>
        <span className={`shrink-0 rounded-full px-2.5 py-1 text-[11px] font-bold ${FEE_STATUS_STYLE[inv.status] ?? ""}`}>
          {FEE_STATUS_LABEL[inv.status] ?? inv.status.toUpperCase()}
        </span>
      </div>
      <div className="mt-2 flex flex-wrap items-baseline gap-x-3 gap-y-1 text-sm">
        <span>Freight <strong>{money(inv.freightAmount)}</strong></span>
        <span>Fee (10%) <strong className="neon-text font-condensed text-xl">{money(inv.feeAmount)}</strong></span>
        <span>Paid <strong>{money(inv.paidAmount)}</strong></span>
        {unpaid && <span>Due <strong className="text-[var(--accent)]">{money(inv.balanceDue)}</strong> · {inv.daysOutstanding} day{inv.daysOutstanding === 1 ? "" : "s"} outstanding</span>}
        {inv.status === "paid" && inv.paidAt && <span className="text-[var(--dim)]">Settled {new Date(inv.paidAt).toLocaleDateString([], { month: "short", day: "numeric" })}</span>}
      </div>
      {(inv.everWarned || inv.everRevoked) && (
        <p className="mt-1.5 text-xs font-semibold text-amber-200">
          {inv.everRevoked ? "⛔ This fee passed day 10 unpaid — board permission was revoked until it settled. " : ""}
          {inv.everWarned && !inv.everRevoked ? "⚠ This fee passed day 7 unpaid — warning on the carrier's record. " : ""}
          {inv.status === "paid" ? "Standing is restored; the late history stays on the record." : ""}
        </p>
      )}
      {inv.payments.length > 0 && (
        <ul className="mt-2 space-y-1 text-xs text-[var(--dim)]">
          {inv.payments.map((p) => (
            <li key={p.id} className="rounded-lg bg-[var(--surface)] px-2.5 py-1.5">
              💵 {money(p.amount)} by {p.rail === "ach" ? "ACH" : p.rail === "debit" ? "debit card" : "crypto"} · ref{" "}
              <span className="break-all font-mono">{p.reference}</span> · {new Date(p.paidAt).toLocaleDateString([], { month: "short", day: "numeric" })}
              {" · "}{p.verification === "onchain_verified" ? "verified on-chain" : p.verification.replace(/_/g, " ")} · recorded by @{p.recordedBy}
            </li>
          ))}
        </ul>
      )}
      {unpaid && <FeeRailsBlock inv={inv} onPayByCard={canRecord ? payByCard : undefined} />}
      {unpaid && canRecord && (
        <div className="mt-3 border-t border-[var(--border)] pt-3">
          <div className="text-xs font-bold uppercase tracking-wide text-[var(--dim)]">RUGGS LOGISTICS DISPATCH SUPPORT — record a payment</div>
          <div className="mt-2 flex flex-wrap items-center gap-2">
            <label className="sr-only" htmlFor={`fee-rail-${inv.id}`}>Payment rail</label>
            <select
              id={`fee-rail-${inv.id}`}
              className="rounded-lg border border-[var(--border)] bg-[var(--surface)] px-2 py-2.5 text-sm font-semibold"
              value={rail}
              onChange={(e) => setRail(e.target.value as "ach" | "debit" | "crypto")}
              aria-label={`Payment rail for load ${inv.loadId} dispatch fee`}
            >
              <option value="ach">ACH</option>
              <option value="debit">Debit card</option>
              <option value="crypto">Crypto</option>
            </select>
            <label className="sr-only" htmlFor={`fee-ref-${inv.id}`}>Payment reference</label>
            <input
              id={`fee-ref-${inv.id}`}
              className="min-w-40 flex-1 rounded-lg border border-[var(--border)] bg-[var(--surface)] px-3 py-2.5 text-sm"
              placeholder={rail === "crypto" ? "Transaction hash" : rail === "ach" ? "ACH trace number" : "Card receipt reference"}
              value={reference}
              onChange={(e) => setReference(e.target.value)}
              aria-label={`Payment reference for load ${inv.loadId} dispatch fee`}
            />
            <label className="sr-only" htmlFor={`fee-amt-${inv.id}`}>Payment amount</label>
            <input
              id={`fee-amt-${inv.id}`}
              className="w-28 rounded-lg border border-[var(--border)] bg-[var(--surface)] px-3 py-2.5 text-sm"
              inputMode="decimal"
              placeholder={inv.balanceDue.toFixed(2)}
              value={amount}
              onChange={(e) => setAmount(e.target.value)}
              aria-label={`Payment amount for load ${inv.loadId} dispatch fee (blank means the full balance)`}
            />
            <button
              type="button"
              disabled={busy || !reference.trim()}
              className="btn-neon btn-press rounded-xl px-4 py-2.5 text-sm font-bold disabled:opacity-50"
              aria-label={`Record dispatch fee payment for load ${inv.loadId}`}
              onClick={() => {
                setBusy(true);
                const amt = parseFloat(amount.replace(/[^0-9.]/g, ""));
                void api
                  .recordDispatchFeePayment({
                    loadId: inv.loadId,
                    rail,
                    reference: reference.trim(),
                    paidAt: null,
                    amount: Number.isFinite(amt) && amt > 0 ? amt : null,
                    chain: rail === "crypto" ? "robinhood" : null,
                  })
                  .then((res) => {
                    if (!res.ok) {
                      setBanner(res.error ?? "That payment didn't record.");
                      return;
                    }
                    setBanner(
                      res.invoice?.status === "paid"
                        ? `Dispatch fee on load #${inv.loadId} paid in full — @${inv.carrierUsername}'s board gate is open again.`
                        : `Payment recorded on load #${inv.loadId} — a balance is still due, so the gate stays closed until it's paid in full.`,
                    );
                    setReference("");
                    setAmount("");
                    onRecorded();
                  })
                  .catch(() => setBanner("That payment didn't record — check your connection and try again."))
                  .finally(() => setBusy(false));
              }}
            >
              {busy ? "Recording…" : "Record payment"}
            </button>
          </div>
          <p className="mt-1.5 text-xs text-[var(--dim)]">
            Blank amount records the full balance due. Partial payments record but do not reopen the board — paid in
            full is what clears the gate.
          </p>
        </div>
      )}
    </article>
  );
}

/** My dispatch-fee invoices (carrier-facing, under the board). */
export function MyDispatchFeesPanel({ setBanner }: { setBanner: (s: string | null) => void }) {
  const queryClient = useQueryClient();
  const feesQuery = useQuery({ queryKey: ["my-dispatch-fees"], queryFn: () => api.getMyDispatchFees({}) });
  const boardQuery = useQuery({ queryKey: ["load-board"], queryFn: () => api.getLoadBoard({}) });
  const invoices = feesQuery.data?.invoices ?? [];
  if (feesQuery.isPending || invoices.length === 0) return null;
  const canRecord = boardQuery.data?.canPost ?? false;
  const refresh = () => {
    void queryClient.invalidateQueries({ queryKey: ["my-dispatch-fees"] });
    void queryClient.invalidateQueries({ queryKey: ["load-board"] });
    void queryClient.invalidateQueries({ queryKey: ["dispatch-fee-ledger"] });
  };
  return (
    <section className="space-y-2.5" aria-label="My dispatch fees">
      <h3 className="font-condensed text-xl font-semibold">💰 Dispatch fees — RUGGS LLC 10% per board load</h3>
      <p className="text-sm text-[var(--dim)]">
        Every load you claim off this board owes RUGGS LLC a 10% dispatch fee on the load's final freight amount, invoiced
        automatically when the delivery POD seals. Pay by ACH, debit, or crypto — the gate reopens the moment a fee is
        paid in full. Day 7 unpaid stamps a warning on your record; day 10 revokes board permission until the debt is
        settled.
      </p>
      {invoices.map((inv) => (
        <FeeInvoiceCard key={inv.id} inv={inv} canRecord={canRecord} setBanner={setBanner} onRecorded={refresh} />
      ))}
    </section>
  );
}

