/** The board post form's persisted snapshot, parsed once per page
 *  load (loadDraftPersistence.ts) — same survival rule as the
 *  Add-a-load form: a webview recycle mid-entry restores the post
 *  exactly, attached document included, instead of vanishing it. */
let restoredBoardFormCache: LoadFormSnapshot<Draft> | null | undefined;
function restoredBoardForm(): LoadFormSnapshot<Draft> | null {
  if (restoredBoardFormCache === undefined) {
    try {
      restoredBoardFormCache = parseFormSnapshot(localStorage.getItem(BOARD_DRAFT_KEY), EMPTY_DRAFT);
    } catch {
      restoredBoardFormCache = null;
    }
  }
  return restoredBoardFormCache;
}

function laneOf(r: { pickupCity: string | null; pickupState: string | null; deliveryCity: string | null; deliveryState: string | null }): string {
  const a = [r.pickupCity, r.pickupState].filter(Boolean).join(", ") || "Pickup TBD";
  const b = [r.deliveryCity, r.deliveryState].filter(Boolean).join(", ") || "Delivery TBD";
  return `${a} → ${b}`;
}

