// Phase 2a — schema dialect transform.
//
// Reads server/src/schema-sqlite.ts (the verbatim Phase 1 SQLite schema)
// and writes server/src/schema-pg.ts: the same tables in
// drizzle-orm/pg-core dialect. The transform is purely textual because the
// source schema uses a small, fully regular set of declaration shapes
// (verified by enumeration before this script was written):
//
//   integer("x", { mode: "boolean" })     -> boolean("x")
//   integer("x", { mode: "timestamp_ms" })-> timestamp("x", { withTimezone: true, mode: "date" })
//   integer("x").primaryKey({ autoIncrement: true }) -> serial("x").primaryKey()
//   integer("x")                          -> integer("x")        (unchanged)
//   real("x")                             -> doublePrecision("x") (SQLite REAL is float8;
//                                             pg `real` is float4 and would lose cents)
//   text(...)                             -> text(...)            (unchanged; enum opts carry over)
//   sqliteTable(                          -> pgTable(
//
// Every replacement is counted and asserted; any leftover SQLite marker
// fails the run loudly instead of emitting a half-converted schema.
// Counts updated at the Phase 2 merge (auth Phase 2b schema additions:
// +7 auth tables, +1 boolean (accounts.is_owner), +22 timestamp_ms,
// +7 autoincrement PKs; REAL unchanged). Migration 0109 (board
// assignment flow) adds +3 timestamp_ms (board_loads pickup/delivery
// appointments + decline time); its text columns ride the unchanged
// text rule. Migration 0110 (send door) adds +2 timestamp_ms
// (broker_submissions pickup/delivery appointments). Migration 0111
// (library document sends) adds +1 table, +1 autoincrement PK, +2
// timestamp_ms (document_sends created/sent). Migration 0112
// (receive links) adds +1 table, +1 autoincrement PK, +2 timestamp_ms
// (receive_links created/revoked).
//
//   bun run host/pg/transform-schema.ts

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dir, "..", "..");
const SRC = path.join(ROOT, "server", "src", "schema-sqlite.ts");
const OUT = path.join(ROOT, "server", "src", "schema-pg.ts");

let src = readFileSync(SRC, "utf8");

function count(re: RegExp, s: string): number {
  return (s.match(re) ?? []).length;
}

function replaceAll(
  label: string,
  re: RegExp,
  to: string,
  expected: number,
): void {
  const found = count(re, src);
  if (found !== expected) {
    throw new Error(
      `[transform] ${label}: expected ${expected} occurrences, found ${found} — aborting`,
    );
  }
  src = src.replace(re, to);
  console.log(`[transform] ${label}: ${found}`);
}

// Header comment: swap the dialect line in the file's own doc comment.
src = src.replace(
  "// Drizzle schema for STONEMILES.",
  "// Drizzle schema for STONEMILES — POSTGRES dialect.\n" +
    "//\n" +
    "// GENERATED by host/pg/transform-schema.ts from schema-sqlite.ts.\n" +
    "// Do not hand-edit: edit the SQLite source (or the transform) and\n" +
    "// regenerate. Type mapping: integer booleans -> boolean, integer\n" +
    "// ms-epoch timestamps -> timestamptz (mode date), autoincrement PKs ->\n" +
    "// serial, REAL -> double precision (float8 fidelity), text -> text.",
);

// Import line.
replaceAll(
  "import line",
  /import \{ integer, real, sqliteTable, text \} from "drizzle-orm\/sqlite-core";/,
  'import {\n  boolean,\n  doublePrecision,\n  integer,\n  pgTable,\n  serial,\n  text,\n  timestamp,\n} from "drizzle-orm/pg-core";',
  1,
);

// Order matters: mode-ful integers first, then autoincrement PKs, then
// the table builder and REAL.
replaceAll(
  'integer mode "boolean" -> boolean',
  /integer\(("[a-z0-9_]+"), \{ mode: "boolean" \}\)/g,
  "boolean($1)",
  106,
);
replaceAll(
  'integer mode "timestamp_ms" -> timestamp(tz, date)',
  /integer\(("[a-z0-9_]+"), \{ mode: "timestamp_ms" \}\)/g,
  'timestamp($1, { withTimezone: true, mode: "date" })',
  296,
);
replaceAll(
  "autoincrement PK -> serial",
  /integer\(("[a-z0-9_]+")\)\.primaryKey\(\{ autoIncrement: true \}\)/g,
  "serial($1).primaryKey()",
  131,
);
replaceAll("sqliteTable -> pgTable", /\bsqliteTable\(/g, "pgTable(", 161);
replaceAll("real -> doublePrecision", /\breal\(/g, "doublePrecision(", 172);

// Leftovers: any of these means the source schema grew a shape this
// transform does not know. Fail, don't guess.
const leftovers: Array<[string, RegExp]> = [
  ["sqlite-core", /sqlite-core/],
  ["sqliteTable", /sqliteTable/],
  ["timestamp_ms", /timestamp_ms/],
  ["autoIncrement", /autoIncrement/],
  ['mode: "boolean"', /mode: "boolean"/],
];
for (const [label, re] of leftovers) {
  const n = count(re, src);
  if (n !== 0) {
    throw new Error(`[transform] leftover ${label}: ${n} — aborting, no file written`);
  }
}

writeFileSync(OUT, src);
console.log(`[transform] wrote ${OUT}`);
