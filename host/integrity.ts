// STONEMILES SENTRY — integrity verification (2026-11-17).
//
// Two questions this answers on demand (host/verify-integrity.ts):
//
//   1. TRUE RECORDS: is the sealed hash chain in the database
//      still exactly the chain appendChain wrote? Recomputed
//      link by link with the EXISTING verifier
//      (server/src/verifyAudit.ts verifyChainEntries — the same
//      code the Verify & Audit hub runs), over chain_log read
//      fresh from the database. First broken link wins and is
//      identified by id / ref / event.
//
//   2. TRUE CODE: does the code on disk still match the
//      fingerprint taken when it shipped? host/integrity-
//      manifest.json holds a sha256 of every file under host/
//      and server/src/ (tests and the manifest itself excluded)
//      plus bun.lock. Recompute and diff: any drifted, added, or
//      missing file is named. The manifest is generated by
//      `bun run host/verify-integrity.ts --write-manifest` at
//      ship time and travels with the code it fingerprints.
//
// Pure/diff logic lives here and is unit-tested; the CLI is a
// thin shell over it.

import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";
import { asc } from "drizzle-orm";
import * as schema from "../server/src/schema";
import {
  verifyChainEntries,
  type ChainVerification,
} from "../server/src/verifyAudit";

export function sha256Hex(data: Uint8Array | string): string {
  return createHash("sha256").update(data).digest("hex");
}

async function sha256Text(text: string): Promise<string> {
  return sha256Hex(new TextEncoder().encode(text));
}

// ---------------------------------------------------------------------------
// Sealed-chain verification
// ---------------------------------------------------------------------------

/** Re-verify the whole sealed chain from a database handle (the
 *  host ctx getDb() shape). Reads chain_log in chain order and
 *  runs the existing verifier unchanged. */
export async function verifyChainFromDb(
  db: ReturnType<typeof import("./ctx").getDb>,
): Promise<ChainVerification> {
  const rows = await db
    .select()
    .from(schema.chainLog)
    .orderBy(asc(schema.chainLog.id));
  return verifyChainEntries(
    rows.map((r) => ({
      id: r.id,
      refKind: r.refKind,
      refId: r.refId,
      event: r.event,
      payload: r.payload,
      prevHash: r.prevHash,
      hash: r.hash,
      createdAt: r.createdAt.toISOString(),
    })),
    sha256Text,
    "GENESIS",
  );
}

// ---------------------------------------------------------------------------
// Code fingerprint manifest
// ---------------------------------------------------------------------------

export interface IntegrityManifest {
  version: 1;
  /** ISO timestamp of generation — informational; diffs ignore it. */
  generatedAt: string;
  /** POSIX-style path (relative to the repo root) → sha256 hex. */
  files: Record<string, string>;
}

export const MANIFEST_REL_PATH = "host/integrity-manifest.json";

const MANIFEST_SCAN_DIRS = ["host", "server/src"] as const;

function isTestFile(relPath: string): boolean {
  return /\.test\.(ts|tsx|js|mjs)$/.test(relPath);
}

function walk(dirAbs: string, rootAbs: string, out: string[]): void {
  for (const entry of readdirSync(dirAbs, { withFileTypes: true })) {
    const abs = path.join(dirAbs, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name === ".git") continue;
      walk(abs, rootAbs, out);
    } else if (entry.isFile()) {
      out.push(path.relative(rootAbs, abs).split(path.sep).join("/"));
    }
  }
}

/** Every fingerprint-covered file under root, sorted: all of
 *  host/ and server/src/ except tests and the manifest itself,
 *  plus bun.lock. */
export function collectCodeFiles(rootAbs: string): string[] {
  const out: string[] = [];
  for (const dir of MANIFEST_SCAN_DIRS) {
    const abs = path.join(rootAbs, dir);
    if (existsSync(abs)) walk(abs, rootAbs, out);
  }
  if (existsSync(path.join(rootAbs, "bun.lock"))) out.push("bun.lock");
  return out
    .filter((rel) => rel !== MANIFEST_REL_PATH && !isTestFile(rel))
    .sort();
}

/** Fingerprint the tree under root as it stands right now. */
export function buildManifest(rootAbs: string, now = new Date()): IntegrityManifest {
  const files: Record<string, string> = {};
  for (const rel of collectCodeFiles(rootAbs)) {
    files[rel] = sha256Hex(readFileSync(path.join(rootAbs, rel)));
  }
  return { version: 1, generatedAt: now.toISOString(), files };
}

export type ManifestDiff = {
  /** Present in both, hash differs — the file changed. */
  changed: string[];
  /** On disk now, absent from the manifest — a file appeared. */
  added: string[];
  /** In the manifest, absent on disk — a file vanished. */
  removed: string[];
};

export function diffManifest(
  expected: IntegrityManifest,
  actual: IntegrityManifest,
): ManifestDiff {
  const changed: string[] = [];
  const added: string[] = [];
  const removed: string[] = [];
  for (const [rel, hash] of Object.entries(actual.files)) {
    if (!(rel in expected.files)) added.push(rel);
    else if (expected.files[rel] !== hash) changed.push(rel);
  }
  for (const rel of Object.keys(expected.files)) {
    if (!(rel in actual.files)) removed.push(rel);
  }
  return { changed: changed.sort(), added: added.sort(), removed: removed.sort() };
}

export function manifestIsIntact(diff: ManifestDiff): boolean {
  return diff.changed.length === 0 && diff.added.length === 0 && diff.removed.length === 0;
}

/** Read + parse a manifest file; null when absent or malformed. */
export function readManifest(manifestAbs: string): IntegrityManifest | null {
  try {
    if (!existsSync(manifestAbs)) return null;
    const parsed = JSON.parse(readFileSync(manifestAbs, "utf8")) as IntegrityManifest;
    if (parsed.version !== 1 || typeof parsed.files !== "object" || parsed.files === null) {
      return null;
    }
    return parsed;
  } catch {
    return null;
  }
}

/** statSync re-export for the CLI's DB presence check. */
export function fileSize(abs: string): number | null {
  try {
    return statSync(abs).size;
  } catch {
    return null;
  }
}
