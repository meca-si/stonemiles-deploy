	`id` integer PRIMARY KEY AUTOINCREMENT NOT NULL,
	`username` text NOT NULL,
	`load_id` integer,
	`permit_number` text,
	`issuing_state` text,
	`issuing_agency` text,
	`route_steps` text NOT NULL,
	`route_places` text NOT NULL,
	`height_text` text,
	`width_text` text,
	`length_text` text,
	`weight_text` text,
	`height_in` real,
	`width_in` real,
	`length_in` real,
	`weight_lbs` real,
	`valid_from` text,
	`valid_to` text,
	`escorts` text,
	`curfews` text NOT NULL,
	`restrictions` text NOT NULL,
	`qr_text` text,
	`doc_blob_key` text,
	`doc_mime` text,
	`doc_sha256` text,
	`filed_copy_id` integer,
	`completed_at` integer,
	`created_at` integer NOT NULL,
	`updated_at` integer NOT NULL
);
